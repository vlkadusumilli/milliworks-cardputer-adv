"""Make the Breathe app's spoken cues with macOS text-to-speech.

    python3 tools/make_voice.py

For each phrase: `say` records it, `afconvert` turns it into 16 kHz mono 16-bit audio,
then this script trims the silence, adds 8 ms fades (no clicks), levels the peak to
-3 dBFS and writes:
  - design/sd/milliWorks/breathe/voices/samantha/*.wav  full quality (16 kHz 16-bit): copy this
                                               folder to the SD card
  - src/voice_builtin.h        a small phone-quality copy (8 kHz 8-bit, ~13 KB) built into
                               the firmware, used whenever the SD voice isn't there
  - design/sounds/voice_*.wav  both versions, to listen to and for the preview
"""
import os
import subprocess
import sys
import tempfile
import wave
from array import array

VOICE, RATE_WPM, SR = "Samantha", 130, 16000
PHRASES = [("in", "Breathe in."), ("hold", "Hold."), ("out", "Breathe out.")]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def record(text, tmp):
    aiff, wav = os.path.join(tmp, "v.aiff"), os.path.join(tmp, "v.wav")
    subprocess.run(["say", "-v", VOICE, "-r", str(RATE_WPM), "-o", aiff, text], check=True)
    subprocess.run(["afconvert", "-f", "WAVE", "-d", f"LEI16@{SR}", "-c", "1", aiff, wav], check=True)
    with wave.open(wav) as w:
        assert w.getframerate() == SR and w.getnchannels() == 1 and w.getsampwidth() == 2
        return array("h", w.readframes(w.getnframes()))


def tidy(s):
    peak = max(abs(x) for x in s) or 1
    thr = peak * 0.02                                   # trim quiet lead-in and tail
    a = next(i for i, x in enumerate(s) if abs(x) > thr)
    b = len(s) - next(i for i, x in enumerate(reversed(s)) if abs(x) > thr)
    a, b = max(0, a - SR // 50), min(len(s), b + SR // 20)  # keep 20 ms before, 50 ms after
    s = s[a:b]
    gain = (32767 * 0.708) / peak                       # -3 dBFS
    fade = SR * 8 // 1000
    out = array("h")
    for i, x in enumerate(s):
        f = min(1.0, i / fade, (len(s) - 1 - i) / fade)
        out.append(int(max(-32767, min(32767, x * gain * f))))
    return out


def main():
    clips = {}
    with tempfile.TemporaryDirectory() as tmp:
        for key, text in PHRASES:
            clips[key] = tidy(record(text, tmp))
    sd_dir = os.path.join(ROOT, "design", "sd", "milliWorks", "breathe", "voices", "samantha")
    snd_dir = os.path.join(ROOT, "design", "sounds")
    os.makedirs(sd_dir, exist_ok=True); os.makedirs(snd_dir, exist_ok=True)
    small = {}
    for key, s in clips.items():
        for path in (os.path.join(sd_dir, f"{key}.wav"), os.path.join(snd_dir, f"voice_{key}.wav")):
            with wave.open(path, "wb") as w:
                w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(s.tobytes())
        # Built-in copy: low-pass (3-tap) then take every 2nd sample -> 8 kHz, then 8-bit unsigned.
        lp = [(s[max(i - 1, 0)] + 2 * s[i] + s[min(i + 1, len(s) - 1)]) / 4 for i in range(len(s))]
        b = bytes(max(0, min(255, int(round(lp[i] / 256)) + 128)) for i in range(0, len(lp), 2))
        small[key] = b
        with wave.open(os.path.join(snd_dir, f"voice_builtin_{key}.wav"), "wb") as w:
            w.setnchannels(1); w.setsampwidth(1); w.setframerate(SR // 2); w.writeframes(b)
    lines = [
        "// voice_builtin.h - the Breathe voice, phone quality, built into the firmware as a",
        "// fallback. GENERATED by tools/make_voice.py (macOS voice '" + VOICE + "',",
        f"// {SR // 2} Hz, 8-bit unsigned, 128 = silence). Full quality lives on the SD card.",
        "#pragma once",
        "#include <stdint.h>",
        f"static const uint32_t VOICE_BUILTIN_RATE = {SR // 2};",
    ]
    for key, b in small.items():
        lines.append(f"static const uint8_t VOICE_BUILTIN_{key.upper()}[{len(b)}] = {{{','.join(str(x) for x in b)}}};")
    open(os.path.join(ROOT, "src", "voice_builtin.h"), "w").write("\n".join(lines) + "\n")
    for key, s in clips.items():
        print(f"  {key:5} {len(s) / SR:.2f} s   SD: {len(s) * 2 // 1024} KB   built-in: {len(small[key]) // 1024} KB")
    print(f"  built into the firmware: {sum(len(b) for b in small.values()) // 1024} KB;  SD folder: {os.path.relpath(sd_dir, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
