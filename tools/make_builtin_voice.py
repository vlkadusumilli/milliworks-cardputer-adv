"""Build the small voice inside the firmware (src/voice_builtin.h) from an SD voice.

    python3 tools/make_builtin_voice.py luna

Takes design/sd/milliWorks/breathe/voices/<name>/{in,hold,out}.wav (16 kHz, 16-bit), cuts
the quiet tail, filters and resamples to 6 kHz 8-bit (small, phone-like quality: it is
only the fallback when the SD voice is missing) and writes:
  - src/voice_builtin.h                    built into the firmware
  - design/sounds/voice_builtin_*.wav      to listen to on the Mac
"""
import math
import os
import sys
import wave
from array import array

OUT_SR = 6000
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(path):
    with wave.open(path) as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2
        return w.getframerate(), array("h", w.readframes(w.getnframes()))


def trim_tail(s, sr, keep_ms=40):
    win = sr // 100
    rms = [(sum(x * x for x in s[i:i + win]) / win) ** 0.5 for i in range(0, len(s), win)]
    thr = max(rms) * 0.06
    last = max(i for i, r in enumerate(rms) if r > thr)
    return s[:min(len(s), (last + 1) * win + sr * keep_ms // 1000)]


def resample(s, sr):
    # Windowed-sinc low-pass at 0.45 x the new rate, then pick samples at the new rate.
    cut = 0.45 * OUT_SR / sr
    taps = 63
    h = []
    for n in range(taps):
        m = n - taps // 2
        sinc = 2 * cut if m == 0 else math.sin(2 * math.pi * cut * m) / (math.pi * m)
        h.append(sinc * (0.54 - 0.46 * math.cos(2 * math.pi * n / (taps - 1))))
    total = sum(h)
    h = [x / total for x in h]
    out = []
    n_out = int(len(s) * OUT_SR / sr)
    for i in range(n_out):
        c = i * sr / OUT_SR
        a = int(c)
        acc = 0.0
        for k in range(taps):
            j = a + k - taps // 2
            if 0 <= j < len(s):
                acc += s[j] * h[k]
        out.append(acc)
    peak = max(abs(x) for x in out) or 1
    fade = OUT_SR * 8 // 1000
    res = bytearray()
    for i, x in enumerate(out):
        f = min(1.0, i / fade, (len(out) - 1 - i) / fade)
        res.append(max(0, min(255, int(round(x * f * (32767 * 0.708 / peak) / 256)) + 128)))
    return bytes(res)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    name = sys.argv[1]
    src = os.path.join(ROOT, "design", "sd", "milliWorks", "breathe", "voices", name)
    lines = [
        "// voice_builtin.h - the Breathe voice built into the firmware, used when the SD voice",
        f"// is missing. GENERATED by tools/make_builtin_voice.py from the '{name}' SD voice",
        f"// ({OUT_SR} Hz, 8-bit unsigned, 128 = silence). Full quality lives on the SD card.",
        "#pragma once",
        "#include <stdint.h>",
        f"static const uint32_t VOICE_BUILTIN_RATE = {OUT_SR};",
    ]
    total = 0
    for key in ("in", "hold", "out"):
        sr, s = read(os.path.join(src, f"{key}.wav"))
        b = resample(trim_tail(s, sr), sr)
        total += len(b)
        lines.append(f"static const uint8_t VOICE_BUILTIN_{key.upper()}[{len(b)}] = {{{','.join(str(x) for x in b)}}};")
        with wave.open(os.path.join(ROOT, "design", "sounds", f"voice_builtin_{key}.wav"), "wb") as w:
            w.setnchannels(1); w.setsampwidth(1); w.setframerate(OUT_SR); w.writeframes(b)
        print(f"{key}: {len(b) / OUT_SR:.2f} s, {len(b)} bytes")
    open(os.path.join(ROOT, "src", "voice_builtin.h"), "w").write("\n".join(lines) + "\n")
    print(f"src/voice_builtin.h: {total} bytes of sound")


if __name__ == "__main__":
    main()
